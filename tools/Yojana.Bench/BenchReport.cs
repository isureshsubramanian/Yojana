using System.Globalization;
using System.Text;
using System.Text.Json;

namespace Yojana.Bench;

/// <summary>Collects facts and measurements, then writes them as Markdown and JSON under the output directory.</summary>
public sealed class BenchReport(BenchOptions options)
{
    private readonly List<(string Section, string Key, string Value)> facts = [];
    private readonly List<Measurement> measurements = [];
    private readonly StringBuilder log = new();
    public readonly DateTime StartedAt = DateTime.UtcNow;

    public sealed record Measurement(string Slo, string Target, string Observed, string Verdict, string Notes);

    public void Fact(string section, string key, object? value)
    {
        var text = value switch { null => "—", IFormattable f => f.ToString(null, CultureInfo.InvariantCulture), _ => value.ToString() ?? "—" };
        facts.Add((section, key, text));
        Console.WriteLine($"  {section} · {key}: {text}");
    }

    public void Measure(string slo, string target, string observed, string verdict, string notes = "")
    {
        measurements.Add(new Measurement(slo, target, observed, verdict, notes));
        Console.WriteLine($"  [{verdict}] {slo} → {observed} (target {target}){(notes.Length > 0 ? " · " + notes : "")}");
    }

    public void Log(string line)
    {
        var stamped = $"{DateTime.UtcNow:HH:mm:ss} {line}";
        Console.WriteLine(stamped);
        log.AppendLine(stamped);
    }

    public static string Ms(double ms) => ms < 10 ? ms.ToString("0.00", CultureInfo.InvariantCulture) + " ms" : ms < 1000 ? ms.ToString("0.0", CultureInfo.InvariantCulture) + " ms" : (ms / 1000).ToString("0.00", CultureInfo.InvariantCulture) + " s";

    public static (double P50, double P95, double P99, double Max, double Mean) Percentiles(IReadOnlyList<double> samples)
    {
        if (samples.Count == 0) return (0, 0, 0, 0, 0);
        var sorted = samples.OrderBy(x => x).ToArray();
        double At(double p) => sorted[Math.Min(sorted.Length - 1, Math.Max(0, (int)Math.Ceiling(p * sorted.Length) - 1))];
        return (At(0.50), At(0.95), At(0.99), sorted[^1], sorted.Average());
    }

    public async Task WriteAsync()
    {
        Directory.CreateDirectory(options.OutDirectory);
        var stamp = StartedAt.ToString("yyyyMMdd-HHmm", CultureInfo.InvariantCulture);
        var md = new StringBuilder();
        md.AppendLine($"# Storage benchmark run {StartedAt:yyyy-MM-dd HH:mm} UTC · {options.Command}");
        md.AppendLine();
        md.AppendLine($"Target `{options.Server}` database `{options.Database}` · requested {options.Units:N0} units, {options.Events:N0} events on the main tenant, {options.Tenants} tenants, {options.Partitions} partitions · {options.Samples} samples per latency series. Generated by `tools/Yojana.Bench`.");
        md.AppendLine();
        foreach (var section in facts.Select(f => f.Section).Distinct())
        {
            md.AppendLine($"## {section}");
            md.AppendLine();
            md.AppendLine("| | |");
            md.AppendLine("|---|---|");
            foreach (var (_, key, value) in facts.Where(f => f.Section == section)) md.AppendLine($"| {key} | {value} |");
            md.AppendLine();
        }

        if (measurements.Count > 0)
        {
            md.AppendLine("## SLO table");
            md.AppendLine();
            md.AppendLine("| SLO | Target | Observed | Verdict | Notes |");
            md.AppendLine("|---|---|---|---|---|");
            foreach (var m in measurements) md.AppendLine($"| {m.Slo} | {m.Target} | {m.Observed} | {m.Verdict} | {m.Notes} |");
            md.AppendLine();
        }

        md.AppendLine("## Log");
        md.AppendLine();
        md.AppendLine("```");
        md.Append(log);
        md.AppendLine("```");
        var mdPath = Path.Combine(options.OutDirectory, $"bench-{stamp}-{options.Command}.md");
        await File.WriteAllTextAsync(mdPath, md.ToString());
        await File.WriteAllTextAsync(Path.Combine(options.OutDirectory, $"bench-{stamp}-{options.Command}.json"), JsonSerializer.Serialize(new { options.Server, options.Database, options.Units, options.Events, options.Tenants, StartedAt, facts = facts.Select(f => new { f.Section, f.Key, f.Value }), measurements }, new JsonSerializerOptions { WriteIndented = true }));
        Console.WriteLine($"report: {mdPath}");
    }
}
